"""Migration round trip on `imibereho_migrations` only (plan §2.2, §2.3, A3).

upgrade head → downgrade base → upgrade head → `check` (an empty autogenerate diff).
"""

from collections.abc import Iterator

import pytest
from sqlalchemy import CheckConstraint, ForeignKeyConstraint, inspect, text

import app.models  # noqa: F401
from app.core.config import MissingSettingError, Settings, load_settings
from app.db import migrate
from app.db.base import Base
from app.db.guards import UnsafeDatabaseTargetError
from app.db.session import Database


@pytest.fixture(scope="module")
def migrations_settings(exclusive_db_run: None) -> Settings:
    """Taken under the suite's lock (tests/conftest.py), so no other run sees the downgrades."""
    settings = load_settings()
    try:
        settings.database_url_for("migrations")
    except MissingSettingError as exc:
        pytest.exit(f"Migration tests cannot run: {exc}", returncode=2)
    return settings


@pytest.fixture(scope="module")
def migrations_database(migrations_settings: Settings) -> Iterator[Database]:
    try:
        database = Database.for_target(migrations_settings, "migrations")
    except UnsafeDatabaseTargetError as exc:
        pytest.exit(str(exc), returncode=2)
    yield database
    database.dispose()


def tables(database: Database) -> set[str]:
    with database.engine.connect() as connection:
        return set(inspect(connection).get_table_names())


def columns(database: Database, table: str) -> set[str]:
    with database.engine.connect() as connection:
        return {column["name"] for column in inspect(connection).get_columns(table)}


def revision(database: Database) -> str | None:
    with database.engine.connect() as connection:
        if "alembic_version" not in inspect(connection).get_table_names():
            return None
        return connection.execute(text("SELECT version_num FROM alembic_version")).scalar()


def check_constraint_names(database: Database) -> set[tuple[str, str]]:
    with database.engine.connect() as connection:
        inspector = inspect(connection)
        return {
            (table, str(c["name"]))
            for table in inspector.get_table_names()
            if table != "alembic_version"
            for c in inspector.get_check_constraints(table)
        }


def foreign_key_names(database: Database) -> set[tuple[str, str]]:
    with database.engine.connect() as connection:
        inspector = inspect(connection)
        return {
            (table, str(fk["name"]))
            for table in inspector.get_table_names()
            for fk in inspector.get_foreign_keys(table)
        }


def model_check_constraint_names() -> set[tuple[str, str]]:
    return {
        (table.name, str(c.name))
        for table in Base.metadata.tables.values()
        for c in table.constraints
        if isinstance(c, CheckConstraint)
    }


def model_foreign_key_names() -> set[tuple[str, str]]:
    return {
        (table.name, str(c.name))
        for table in Base.metadata.tables.values()
        for c in table.constraints
        if isinstance(c, ForeignKeyConstraint)
    }


def test_round_trip(migrations_settings: Settings, migrations_database: Database) -> None:
    expected = set(Base.metadata.tables)
    migrate.run(migrations_settings, "migrations", "upgrade", "head")
    assert revision(migrations_database) == migrate.head_revision()
    assert expected <= tables(migrations_database)

    migrate.run(migrations_settings, "migrations", "downgrade", "base")
    assert revision(migrations_database) is None
    assert not (expected & tables(migrations_database))

    migrate.run(migrations_settings, "migrations", "upgrade", "head")
    assert revision(migrations_database) == migrate.head_revision()
    # Raises AutogenerateDiffsDetected if the models and the migrated schema differ.
    migrate.run(migrations_settings, "migrations", "check")


def test_stepwise_downgrade_and_upgrade(
    migrations_settings: Settings, migrations_database: Database
) -> None:
    migrate.run(migrations_settings, "migrations", "upgrade", "head")
    assert "role" in columns(migrations_database, "household_accounts")
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0012"
    assert "role" not in columns(migrations_database, "household_accounts")
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0011"
    assert "resilience_plans" not in tables(migrations_database)
    assert "tracker_transactions" in tables(migrations_database)
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0010"
    assert "tracker_transactions" not in tables(migrations_database)
    assert "planned_essentials" in columns(migrations_database, "household_accounts")
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0009"
    assert "planned_essentials" not in columns(migrations_database, "household_accounts")
    assert "identifier" in columns(migrations_database, "household_accounts")
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0008"
    assert "household_accounts" not in tables(migrations_database)
    assert "survey_estimates" in tables(migrations_database)
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0007"
    assert "survey_estimates" not in tables(migrations_database)
    assert "statistical_sources" in tables(migrations_database)
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0006"
    assert "statistical_sources" not in tables(migrations_database)
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0005"
    doubled = {name for _, name in check_constraint_names(migrations_database)}
    assert "ck_districts_ck_districts_code_slug" in doubled  # the names 0006 repairs
    migrate.run(migrations_settings, "migrations", "downgrade", "-1")
    assert revision(migrations_database) == "0004"
    assert "synthetic_households" not in tables(migrations_database)
    migrate.run(migrations_settings, "migrations", "upgrade", "head")
    assert revision(migrations_database) == migrate.head_revision() == "0013"


def test_named_constraints_follow_the_convention(
    migrations_settings: Settings, migrations_database: Database
) -> None:
    migrate.run(migrations_settings, "migrations", "upgrade", "head")
    with migrations_database.engine.connect() as connection:
        inspector = inspect(connection)
        assert inspector.get_pk_constraint("districts")["name"] == "pk_districts"
    # Every CHECK constraint, by name (autogenerate does not compare them; see revision 0006).
    assert check_constraint_names(migrations_database) == model_check_constraint_names()
    assert foreign_key_names(migrations_database) == model_foreign_key_names()


